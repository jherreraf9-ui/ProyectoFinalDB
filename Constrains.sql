-- Validar que no haya cantidades ni precios negativos
ALTER TABLE DETALLECOMPRA ADD CONSTRAINT CHK_DETCOMPRA_CANTIDAD CHECK (CANTIDAD > 0);
ALTER TABLE DETALLECOMPRA ADD CONSTRAINT CHK_DETCOMPRA_PRECIO CHECK (PRECIOUNITARIO >= 0);

-- Validar que los montos en la factura no sean negativos
ALTER TABLE DETALLEFACTURA ADD CONSTRAINT CHK_DETFACTURA_MONTOS CHECK (SUBTOTAL >= 0 AND IMPUESTOS >= 0 AND TOTAL >= 0);

-- Validar que el pago registrado sea mayor a cero
ALTER TABLE DETALLEPAGO ADD CONSTRAINT CHK_DETPAGO_MONTO CHECK (MONTOPAGADO > 0);

-- Validar que el costo base de una reparación no sea negativo
ALTER TABLE TIPOREPARACION ADD CONSTRAINT CHK_TIPOREP_COSTO CHECK (COSTOBASE >= 0);

-- Validar coherencia en el inventario y precios
ALTER TABLE REPUESTOSUMINISTRO ADD CONSTRAINT CHK_REPUESTO_STOCK CHECK (STOCKACTUAL >= 0);
ALTER TABLE REPUESTOSUMINISTRO ADD CONSTRAINT CHK_REPUESTO_COSTOS CHECK (COSTOCOMPRA >= 0 AND PRECIOVENTA >= 0);
ALTER TABLE REPUESTOSUMINISTRO ADD CONSTRAINT CHK_REPUESTO_LOGIC_PRECIO CHECK (PRECIOVENTA >= COSTOCOMPRA);

-- Validar coherencia de fechas en el empleado
ALTER TABLE EMPLEADO ADD CONSTRAINT CHK_EMPLEADO_FECHAS CHECK (FECHAINICIO <= FECHAFIN);

-- Validar que los permisos de roles sean estrictamente 0 o 1 (Booleanos lógicos en Oracle)
ALTER TABLE ROLMENU ADD CONSTRAINT CHK_ROLMENU_LECTURA CHECK (PERMISOLECTURA IN (0, 1));
ALTER TABLE ROLMENU ADD CONSTRAINT CHK_ROLMENU_ESCRITURA CHECK (PERMISOESCRITURA IN (0, 1));
ALTER TABLE ROLMENU ADD CONSTRAINT CHK_ROLMENU_EDICION CHECK (PERMISOEDICION IN (0, 1));
ALTER TABLE ROLMENU ADD CONSTRAINT CHK_ROLMENU_BORRAR CHECK (PERMISOBORRAR IN (0, 1));

-- Evitar que se registre dos veces el mismo Documento de Identificación (DPI/Pasaporte)
ALTER TABLE PERSONA ADD CONSTRAINT UQ_PERSONA_NUMDOC UNIQUE (NOIDENTIFICACION);

-- El nombre de usuario para el login no debe repetirse jamás
ALTER TABLE USUARIO ADD CONSTRAINT UQ_USUARIO_USERNAME UNIQUE (USUARIO);

-- El número de serie físico de un dispositivo debe ser único
ALTER TABLE DISPOSITIVO ADD CONSTRAINT UQ_DISPOSITIVO_NOSERIE UNIQUE (NOSERIE);

-- El NIT del Proveedor también debe ser único
ALTER TABLE PROVEEDOR ADD CONSTRAINT UQ_PROVEEDOR_NIT UNIQUE (NIT);

-- No se puede usar una cantidad de 0 repuestos (o repuestos negativos) en una reparación
ALTER TABLE USOREPUESTO ADD CONSTRAINT CHK_USOREPUESTO_CANTIDAD CHECK (CANTIDAD > 0);

-- La garantía no puede ser de 0 meses o negativa
ALTER TABLE GARANTIA ADD CONSTRAINT CHK_GARANTIA_MESES CHECK (MESESCOBERTURA > 0);

-- El tiempo estimado (en horas o días) debe ser mayor a 0
ALTER TABLE TIEMPOESTIMADO ADD CONSTRAINT CHK_TIEMPOESTIMADO_CANTIDAD CHECK (CANTIDAD > 0);


ALTER TABLE ORDENSERVICIO ADD CONSTRAINT CHK_ORDEN_ACEPTA CHECK (ACEPTAREPARACION IN (0, 1));
