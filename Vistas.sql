-- 1. Vista de Órdenes de Servicio (Ideal para la pantalla principal / Dashboard)
-- Muestra el detalle completo de una orden cruzando 7 tablas diferentes para que sea legible.
CREATE OR REPLACE VIEW VW_ORDENES_SERVICIO AS
SELECT 
    O.IDORDEN,
    O.FECHARECEPCION,
    S.NOMBRESUCURSAL AS SUCURSAL,
    P.NOMBRE1 || ' ' || P.APELLIDO1 AS NOMBRE_CLIENTE,
    MAR.MARCA || ' ' || MOD.MODELO AS DISPOSITIVO,
    D.NOSERIE,
    O.DIAGNOSTICO,
    E.ESTADO
FROM ORDENSERVICIO O
JOIN SUCURSAL S ON O.IDSUCURSAL = S.IDSUCURSAL
JOIN DISPOSITIVO D ON O.IDDISPOSITIVO = D.IDDISPOSITIVO
JOIN MODELO MOD ON D.IDMODELO = MOD.IDMODELO
JOIN MARCA MAR ON MOD.IDMARCA = MAR.IDMARCA
JOIN CLIENTE C ON D.IDCLIENTE = C.IDCLIENTE
JOIN PERSONA P ON C.IDPERSONA = P.IDPERSONA
JOIN ESTADO E ON O.IDESTADO = E.IDESTADO;


-- 2. Vista de Inventario Global de Repuestos
-- Muestra el stock disponible y calcula el valor monetario potencial del inventario por sucursal.
CREATE OR REPLACE VIEW VW_INVENTARIO_REPUESTOS AS
SELECT 
    R.IDREPUESTO,
    S.NOMBRESUCURSAL,
    R.DESCRIPCION,
    R.STOCKACTUAL,
    R.COSTOCOMPRA,
    R.PRECIOVENTA,
    (R.STOCKACTUAL * R.PRECIOVENTA) AS VALOR_INVENTARIO
FROM REPUESTOSUMINISTRO R
JOIN SUCURSAL S ON R.IDSUCURSAL = S.IDSUCURSAL;


-- 3. Vista del Directorio del Personal (Empleados y sus roles/puestos)
-- Une Empleado, Persona, Departamento y Puesto para saber quién trabaja dónde.
CREATE OR REPLACE VIEW VW_DIRECTORIO_EMPLEADOS AS
SELECT 
    E.IDEMPLEADO,
    P.NOMBRE1 || ' ' || P.NOMBRE2 || ' ' || P.APELLIDO1 AS NOMBRE_COMPLETO,
    P.NOIDENTIFICACION AS DPI_DOCUMENTO,
    DEP.DEPARTAMENTO AS AREA_LABORAL,
    PT.PUESTO,
    EST.ESTADO
FROM EMPLEADO E
JOIN PERSONA P ON E.IDPERSONA = P.IDPERSONA
JOIN PUESTO PT ON E.IDPUESTO = PT.IDPUESTO
JOIN DEPARTAMENTOLABORAL DEP ON PT.IDDEPARTAMENTO = DEP.IDDEPARTAMENTO
JOIN ESTADO EST ON E.IDESTADO = EST.IDESTADO;

CREATE OR REPLACE VIEW VW_CONTROL_GARANTIAS AS
SELECT 
    G.IDGARANTIA,
    O.IDORDEN,
    D.NOSERIE,
    MAR.MARCA || ' ' || MOD.MODELO AS EQUIPO,
    TR.DESCRIPCION AS REPARACION_REALIZADA,
    G.FECHAVENCIMIENTO,
    CASE 
        WHEN G.FECHAVENCIMIENTO >= SYSDATE THEN 'ACTIVA'
        ELSE 'VENCIDA'
    END AS ESTADO_GARANTIA
FROM GARANTIA G
JOIN DETALLEREPARACION DR ON G.IDDETALLEREPARACION = DR.IDDETALLEREPARACION
JOIN ORDENSERVICIO O ON DR.IDORDEN = O.IDORDEN
JOIN DISPOSITIVO D ON O.IDDISPOSITIVO = D.IDDISPOSITIVO
JOIN MODELO MOD ON D.IDMODELO = MOD.IDMODELO
JOIN MARCA MAR ON MOD.IDMARCA = MAR.IDMARCA
JOIN TIPOREPARACION TR ON DR.IDTIPOREPARACION = TR.IDTIPOREPARACION;

CREATE OR REPLACE VIEW VW_RESUMEN_FACTURACION AS
SELECT 
    F.IDFACTURA,
    F.FECHA AS FECHA_FACTURA,
    O.IDORDEN,
    P.NOMBRE1 || ' ' || P.APELLIDO1 AS CLIENTE,
    P.NIT,
    E.ESTADO AS ESTADO_PAGO,
    (SELECT SUM(TOTAL) FROM DETALLEFACTURA DF WHERE DF.IDFACTURA = F.IDFACTURA) AS MONTO_TOTAL
FROM FACTURACLIENTE F
JOIN ORDENSERVICIO O ON F.IDORDEN = O.IDORDEN
JOIN DISPOSITIVO D ON O.IDDISPOSITIVO = D.IDDISPOSITIVO
JOIN CLIENTE C ON D.IDCLIENTE = C.IDCLIENTE
JOIN PERSONA P ON C.IDPERSONA = P.IDPERSONA
JOIN ESTADO E ON F.IDESTADO = E.IDESTADO;

CREATE OR REPLACE VIEW VW_ACCESOS_SISTEMA AS
SELECT 
    U.USUARIO AS USERNAME,
    R.NOMBREROL AS ROL,
    M.NOMBREMENU AS MODULO_SISTEMA,
    RM.PERMISOLECTURA AS LEER,
    RM.PERMISOESCRITURA AS ESCRIBIR,
    RM.PERMISOEDICION AS EDITAR,
    RM.PERMISOBORRAR AS BORRAR
FROM USUARIO U
JOIN ROL R ON U.IDROL = R.IDROL
JOIN ROLMENU RM ON R.IDROL = RM.IDROL
JOIN MENU M ON RM.IDMENU = M.IDMENU;

